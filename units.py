_SUPERSCRIPT_MAP = str.maketrans({"²": "2", "³": "3", "⁻": "-", "¹": "1"})

_NUM_UNIT_RE = re.compile(
    r"^([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:\s*(?:[eE][+-]?|\*\s*10\^?)[+-]?\d+)?)\s*(.*)$"
)


def normalize_unit_token(unit_part: str) -> str:
    """Приводит строку единицы к каноническому виду словаря UNIT_CONVERSIONS."""
    if not unit_part:
        return ""
    u = unit_part.strip().replace("\u00a0", " ")
    # Схлопываем пробелы вокруг разделителей: 'м · с' -> 'м·с'
    u = re.sub(r"\s*([·*/])\s*", r"\1", u)
    # 'с-1' -> 'с⁻¹'
    m_exp = re.fullmatch(r"([а-яА-Яa-zA-Z]+)-([1-9])", u)
    if m_exp:
        u = m_exp.group(1) + {"1": "¹", "2": "²", "3": "³"}[m_exp.group(2)]
    u = u.translate(_SUPERSCRIPT_MAP)
    if u in UNIT_CONVERSIONS:
        return u
    if u in _UNIT_FIXUPS:
        u = _UNIT_FIXUPS[u]
    elif u.lower() in _UNIT_FIXUPS:
        u = _UNIT_FIXUPS[u.lower()]
    if u in UNIT_CONVERSIONS:
        return u
    # Фолбэк: регистронезависимый поиск ('ом' -> 'Ом', 'км/ч' vs 'КМ/Ч')
    canon = {k.lower(): k for k in UNIT_CONVERSIONS}
    if u.lower() in canon:
        return canon[u.lower()]
    return u


def parse_value_with_unit(raw_str, is_func: bool = False):
    """
    Разбирает входную строку.
    Для скаляров: возвращает float в СИ.
    Для функций от времени: очищает размерность и возвращает строку выражения.
    """
    if isinstance(raw_str, (int, float)):
        return float(raw_str)

    s = str(raw_str).strip()
    if not s:
        raise ValueError("Ошибка разбора: пустое значение")

    # Unicode-минус и special-пробелы (частый кейс копирования из сборников ЕГЭ)
    s = s.replace("\u2212", "-").replace("\u2009", " ").replace("\u202f", " ").replace("\u00a0", " ")
    # Научная нотация вида 7.2*10^3 / 7.2×10^3 -> 7.2e3
    s = s.replace("×", "*")
    s = re.sub(r"(?<=[\d.])\*\s*10\^?\+?(-?\d+)", lambda m: f"e{m.group(1)}", s)

    # Если это функция или выражение, содержащее переменную t
    if is_func or ("t" in s and not s.isalpha()):
        # Отделяем конечную размерность (например: "6*t м/с^2" -> "6*t")
        parts = s.split()
        if len(parts) > 1 and normalize_unit_token(parts[-1]) in UNIT_CONVERSIONS:
            expr_str = " ".join(parts[:-1])
        elif len(parts) > 1 and not any(ch in parts[-1] for ch in "t0123456789+-*/()"):
            raise ValueError(f"Ошибка разбора: неизвестная единица измерения '{parts[-1]}'")
        else:
            expr_str = s
        return expr_str.strip()

    match = _NUM_UNIT_RE.match(s)
    if not match:
        raise ValueError(f"Ошибка разбора синтаксиса числа: '{raw_str}'")

    num_part, unit_part = match.group(1), match.group(2).strip()
    try:
        val = float(num_part.replace(" ", ""))
    except ValueError:
        raise ValueError(f"Ошибка разбора синтаксиса числа: '{raw_str}'")

    unit_key = normalize_unit_token(unit_part)
    if unit_key not in UNIT_CONVERSIONS:
        raise ValueError(f"Ошибка разбора: неизвестная единица измерения '{unit_part}'")

    mult, offset = UNIT_CONVERSIONS[unit_key]
    return val * mult + offset